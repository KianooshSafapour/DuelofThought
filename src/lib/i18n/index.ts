/** Convert Latin digits to locale digits (fa/ar use Eastern Arabic numerals). */
export function localizeDigits(input: string | number, locale: Locale): string {
  const s = String(input);
  if (locale === 'fa') {
    const faD = ['۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹'];
    return s.replace(/[0-9]/g, (d) => faD[+d]);
  }
  if (locale === 'ar') {
    const arD = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩'];
    return s.replace(/[0-9]/g, (d) => arD[+d]);
  }
  return s;
}
